namespace JinHyung.Data
{
    /// <summary>
    /// 레벨 한 판. 좌표는 전부 <b>원본 world px</b> (y 는 아래가 +).
    ///
    /// <para>
    /// ★★ <b>레벨이 갖는 것은 «발사대 위치와 조준각»뿐이다</b> [3회차 정정].
    /// 2회차가 「파워 곡선·캡도 레벨별」이라고 적었으나 <b>틀렸다</b> — 파워는 전역 기전이고
    /// <see cref="BlumgiConfigData.ForceShootStart"/> 네 상수가 정본이다.
    /// 이 클래스에 <c>PowerCap</c>·<c>MinLaunchHold</c> 같은 컬럼을 다시 만들지 마라.
    /// </para>
    /// </summary>
    public class BlumgiLevelData : IData, IDataKey<int>
    {
        public int Id { get; set; }

        /// <summary>원본 콘솔 ID 와 같은 논리 식별자 — <c>W1L1</c>. 원본 <c>layout._name</c> 과 바이트 단위로 같다.</summary>
        public string Code { get; set; }

        public int WorldNo { get; set; }

        public int LevelNo { get; set; }

        // ★★★ 여기 있던 `LaunchX` · `LaunchY` 는 «지웠다» (패스 ①-h · 12회차 실측).
        //
        //   무엇이 틀렸었나 — 「발사 프레임의 위치」를 <b>레벨 상수</b>로 적어 뒀다.
        //   3회차 주석은 「홀드와 무관하게 고정」이라 했고, 옛 `LaunchY` 주석은
        //   「홀드에 따라 10.7px 내려가지만 함수형이 미측정이라 중앙값을 넣는다」였다.
        //   ⇒ 12회차가 <b>같은 레벨에서 force 를 5점 흔들어</b> 그 함수형을 실측했다:
        //
        //       발사점 = (BallRestX, BallRestY) + (0.2665, 9.8386) · sin(π/2 · min(1, 홀드초/1.5))
        //                                       ↑ 14회차-b 정정 (5레벨 38점 · 잔차 y ≤ 0.066 px)
        //
        //   모델 절편이 «정지 머리공 중심»과 0.07 px 로 붙는다 ⇒ 발사점은 BallRest 에서 나온다.
        //   ★ [14회차-b] 그 관계가 **5레벨 전수**로 확인됐다 — 「W1L3 하나만 봤다」가 해소됐다.
        //   그래서 <b>컬럼 두 개가 통째로 접혔다</b> — 7회차가 감지기 20값을 상수 2개로 접은 것과 같은 종류다.
        //
        //   ⚠ <b>되살리지 마라.</b> 상수 하나로 접으면 «창의 한쪽 끝에서만» 크게 틀린다 —
        //     W1L3 은 옛 상수 233.0 이 force ≈ 66 짜리 값이라 창 하한(force 17.34)에서
        //     원본보다 6.77 px 아래로 쐈고, 그것이 밸런싱 창 대조의 최대 어긋남이었다 (패스 ①-g).
        //     실측 자리는 <see cref="BallRestX"/> · <see cref="BallRestY"/> 이고,
        //     트윈 진폭은 `BlumgiConfigData.LaunchTweenOffsetX/Y`, 시계는 `BlumgiSquashTween` 하나다.

        /// <summary>
        /// ★ <b>조준각의 정본 — 원본 <c>spr_SpriteRotator</c> 인스턴스 변수 0번의 «값 그대로»다</b> [3회차 실측].
        ///
        /// <para>
        /// 궤적에서 피팅한 각도가 아니라 <b>레벨 데이터를 그대로 읽은 것</b>이다.
        /// 화면각은 <see cref="LaunchAngleDeg"/> 로 <c>360 − 값</c> 이다 (C3 각도라 y 아래가 +).
        /// L1 300 · L2 290 · L3 300 · L4 230 이 2·3회차 실측 발사각과 전부 일치한다.
        /// </para>
        ///
        /// <para>
        /// ⚠ 도(°) 가 아니라 <b>원본 변수값</b>이다. 여기에 60·70·130 을 적지 마라 — 원본과 대조가 끊긴다.
        /// </para>
        /// </summary>
        public double AimRotatorValue { get; set; }

        /// <summary>
        /// <see cref="AimRotatorValue"/> 가 <b>추정값</b>인가.
        ///
        /// <para>
        /// ★ <b>이제 전 레벨 <c>false</c> 다.</b> 한때 W1L5 만 <c>true</c> 였다(3회차 덤프 시점에 이미
        /// 레벨을 떠나 있어 인스턴스 변수를 못 읽었다) — <b>4회차와 7회차가 독립으로 <c>330</c> 을 읽어</b>
        /// 해소됐다 (`07 §9-a` · `02 §4-4`). 7회차는 5레벨 전수에서 <c>_a</c> 가 <c>iv[0]</c> 과
        /// <b>5/5 일치</b>함까지 확인했다.
        /// </para>
        ///
        /// <para>
        /// 컬럼을 <b>지우지 않는 이유</b>: 다음 월드가 오면 같은 상황이 다시 생긴다 —
        /// 그때 「추정인지 실측인지」를 적을 자리가 없으면 <b>추정이 실측처럼 섞여 들어간다.</b>
        /// 컨테이너가 <c>true</c> 개수를 세고 채점기가 0 인지 본다.
        /// </para>
        /// </summary>
        public bool AimRotatorEstimated { get; set; }

        /// <summary>
        /// 발사각(도). <b>위쪽이 +</b> — world 속도는 <c>(cos θ, −sin θ) · |v0|</c> 다.
        /// <b>저장 컬럼이 아니라 <see cref="AimRotatorValue"/> 에서 나오는 값</b>이다 —
        /// 같은 각을 두 곳에 두면 어느 쪽이 진실인지 갈린다.
        /// <para>★ <b>홀드와 무관한 레벨 상수다</b> [실측] — W1L4 는 홀드를 100→5000ms 로 50배 흔들어도
        /// 130.0~130.5° 안에 있다. <b>각도를 파워의 함수로 만들지 마라.</b></para>
        /// </summary>
        public double LaunchAngleDeg
        {
            get { return 360.0 - AimRotatorValue; }
        }

        /// <summary>
        /// 발사대 물리 바디 <c>spr_SlimePhysics</c> 의 <b>authored 배치 x</b>
        /// = 인스턴스 변수 <c>iv[0]</c> [★ 20회차 실측 · 5레벨 전수].
        ///
        /// <para>
        /// ★ <b>실제 b2Body x 와 5/5 정확히 같다</b> — 수평 접촉이 없어 x 는 안 움직인다.
        /// 폭이 좌우 대칭이라 bbox 중심 x 이기도 하다.
        /// </para>
        /// </summary>
        public double LauncherBodyX { get; set; }

        /// <summary>
        /// ★★★ 발사대 물리 바디의 <b>authored 배치 y</b> = 인스턴스 변수 <c>iv[1]</c>
        /// [★ 20회차 실측 · 5레벨 전수 — L1 602 · L2 950 · L3 350 · L4 400 · L5 350].
        ///
        /// <para>
        /// ⚠ <b>여기 적힌 값은 «실제 b2Body 위치»가 «아니다».</b> 발사대는 <b>dynamic body</b> 라
        /// 이 자리에서 떨어져 아래 블록 위에 <b>정착</b>한다 — 실제 위치는 5레벨 전부
        /// <c>iv[1]</c> 보다 <b>정확히 5.241 px 위</b>다. 그 정착 위치는 데이터가 아니라
        /// <see cref="BlumgiLevelRuntime.LauncherBodyPosition"/> 이 <b>유도</b>한다.
        /// </para>
        ///
        /// <para>
        /// ★★ <b>왜 정착 위치를 컬럼으로 안 드는가</b> [재발방지 #102 · #53].
        /// 16~19회차는 정착 위치(<c>596.759 · 944.759 · 344.759 · 394.759</c>)를 레벨마다
        /// 적어 두었는데, <b>못 잰 W1L5 한 칸을 반올림 <c>345.0</c> 으로 채워</b> 0.241 px 어긋나 있었다.
        /// 20회차가 다섯 레벨의 잔차를 0 으로 닫아 <b>「데이터가 아니라 유도값」</b>임을 확증했다 —
        /// 그래서 표에서 빼고 기전을 옮긴다. <b>다음 월드는 안 재도 맞는다.</b>
        /// </para>
        ///
        /// <para>
        /// ⚠ 몸통 그림 <c>spr_Slime</c> 은 «정착한» 원점보다 y 로 <b>35 위</b>(= bbox 중심보다 10 위),
        /// x 로 1 오른쪽이다 — 그림 좌표를 배치 원점으로 쓰면 전 레벨이 어긋난다 [UIUX 실측].
        /// </para>
        /// </summary>
        public double LauncherHomeY { get; set; }

        /// <summary>
        /// 머리 위 공 <c>spr_BallVisu</c> 중심 x (94×93) — 발사 «전» 정지 위치다.
        /// ★★ <b>이제 «발사점의 원점»이기도 하다</b> [12회차] — 연출 전용 컬럼이 아니다.
        /// <para>
        /// ★ <b>[14회차-b] 5레벨 전수 재실측으로 소수 3자리까지 갈아 끼웠다</b> —
        /// 6회차가 0.5 단위로 반올림해 둔 값(200 · 259 · 1050 · 986 · 187)은
        /// <b>피팅 절편과 최대 0.42 px 어긋나 있었다.</b> 이 컬럼은 이제 «물리 입력»이라
        /// 반올림이 그대로 발사점 오차가 된다.
        /// </para>
        /// </summary>
        public double BallRestX { get; set; }

        /// <summary>
        /// 머리 위 공 중심 y.
        ///
        /// <para>
        /// ★★★ <b>[12회차] 발사점이 여기서 나온다.</b> 12회차 W1L3 모델의 절편
        /// <b>(1050.108, 224.873)</b> 이 정지 머리공 bbox 중심 <b>(1050.106, 224.806)</b> 과
        /// <b>0.07 px</b> 로 일치했다. 홀드 트윈만큼 아래로 미끄러진 자리가 발사점이다
        /// (<c>BlumgiLevelRuntime.LaunchPositionAt</c>).
        /// </para>
        ///
        /// <para>
        /// ★★★ <b>[14회차-b] 5레벨 실측 — 이 표가 «레벨 데이터의 전부»다</b> (크기는 5레벨 전부 94×93):
        /// W1L1 (200.106, 476.804) · W1L2 (259.239, 817.581) · W1L3 (1050.106, 224.804) ·
        /// W1L4 (985.906, 285.847) · W1L5 (187.047, 261.077).
        /// 자유 피팅 절편과 <b>|Δ| ≤ 0.07 px</b>(1.5 s 초과 이상점 제외 시)로 붙는다.
        /// ⚠ <b>8회차의 「머리공 = 블롭 + (+50.11, −94.96)」 는 60° 레벨(L1·L3)에서만 맞는다</b> —
        /// 5레벨을 나란히 재니 길이는 104.98~107.76 로 같은데 방향이 조준각을 −2.6°~+4.0° 로 «따라간다».
        /// 그래서 <b>오프셋으로 유도하지 않고 이 컬럼을 직접 쓴다.</b>
        /// </para>
        ///
        /// <para>
        /// ⚠ 그래서 <b>이 값은 이제 «연출 좌표»가 아니라 «물리 입력»이다.</b>
        /// 그림을 맞추려고 여기를 흔들면 <b>궤적과 밸런싱 창이 같이 움직인다.</b>
        /// </para>
        ///
        /// <para>
        /// 검산 — 5레벨의 <c>구(舊) LaunchY − BallRestY</c> 가 <b>+6.5 · +9.0 · +8.5 · +7.5 · +9.5</b> 로
        /// 전부 진폭 9.721 «안»이고, 각각을 트윈으로 되돌리면 force <b>48 ~ 81</b> 이 나온다 —
        /// 3회차가 그 레벨을 잰 홀드대와 맞는다. <b>구 상수는 「한 force 에서 뜬 한 점」이었다.</b>
        /// </para>
        /// </summary>
        public double BallRestY { get; set; }

        /// <summary>
        /// 골대 중심 x — <c>spr_BasketTop</c> <b>bbox 중심</b>(212 × 55) [7회차 실측].
        /// <b>골대 6부품이 전부 이 한 점 + 상수 오프셋</b>이라 레벨이 갖는 골대 정보는 이 두 컬럼뿐이다.
        /// </summary>
        public double GoalRimX { get; set; }

        /// <summary>
        /// 골대 중심 y.
        /// ⚠ <b>패스 ①-e 에서 0.5 내려갔다</b> — 기준을 7회차가 뜬 <c>spr_BasketTop</c> bbox 중심으로
        /// 맞췄다. 부품 오프셋도 같이 0.5 올라가므로 <b>부품의 절대 자리는 그대로다</b>
        /// (감지기 4점 · 기둥 2개 전부 실측 bbox 와 일치. 채점기 §5-b 가 기계로 확인한다).
        /// </summary>
        public double GoalRimY { get; set; }

        /// <summary>
        /// 이 레벨의 <b>골인 감지기 좌표가 «유도값»인가</b>.
        ///
        /// <para>
        /// ★★ <b>이제 전 레벨 <c>false</c> 다</b> [7회차 실측]. 6회차가 W1L1 하나만 떠서
        /// 「W1L2~L5 는 림 + W1L1 오프셋으로 «유도»」로 남겼는데, <b>7회차가 5레벨을 나란히 떠서
        /// 오프셋이 소수점까지 같음을 확인</b>했다 — 유도가 맞았던 것이다 (`07 §9-a`).
        /// </para>
        ///
        /// <para>
        /// 컬럼을 <b>지우지 않는 이유</b>: 월드2 이후 레벨은 <b>여전히 미측정</b>이다.
        /// 그 레벨이 데이터에 들어오는 순간 이 플래그가 다시 필요해진다 —
        /// <b>「같을 것」과 「같다」를 구분해 적을 자리</b>다.
        /// </para>
        ///
        /// <para>
        /// ⚠ 7회차 교훈: <b>한 레벨만 뜨면 「상수인지 데이터인지」가 원리적으로 안 갈린다.</b>
        /// 여러 레벨을 나란히 놓고 중심을 빼 봐야 상수가 드러난다.
        /// </para>
        /// </summary>
        public bool DetectorOffsetDerived { get; set; }

        /// <summary>
        /// 테마 배경색 (sRGB hex, <b>원본 값 그대로</b> — Linear 역산 금지).
        ///
        /// <para>
        /// ★★ <b>[20회차] 5레벨 전수가 «전역변수 직독»으로 닫혔다</b> —
        /// <c>LastBackgroundColorArray</c>(0~1 문자열) × 255 가
        /// L1 (228,255,133) · L2 (71,200,255) · L3 (255,219,41) · L4 (255,189,253) · L5 (255,116,82) 이고
        /// <b>우리 5칸과 «정확히» 같다</b> [실측 5레벨 × 4시점 = 20 · 캡처 히스토그램 교차검산].
        /// <b>고칠 것이 없어 안 고쳤다</b> (재발방지 #100).
        /// </para>
        ///
        /// <para>
        /// ⚠⚠ <b>색은 «캡처»가 아니라 «전역변수»로 잰다.</b> 색 트윈은 «화면 픽셀»에만 걸리고
        /// 전역변수는 안 탄다 — 17회차가 캡처로 뜬 W1L2 <c>(76,202,255)</c> 는 <b>트윈 «중간»</b>이었고
        /// 정착값은 <c>(71,200,255)</c> 다. <b>화면색은 «정착 뒤»에만 유효하다.</b>
        /// </para>
        ///
        /// <para>
        /// ⚠ <b>[20회차 · 도구 함정] 게임 캔버스는 <c>getImageData</c> 로 못 읽는다</b> —
        /// WebGL 이고 <c>preserveDrawingBuffer</c> 가 꺼져 있어 20 덤프 전부 <c>(0,0,0)</c> 이 나온다.
        /// <b>화면 픽셀이 필요하면 Playwright 스크린샷</b>을 쓴다.
        /// </para>
        /// </summary>
        public string BgColorHex { get; set; }

        /// <summary>
        /// 배경 격자선의 <b>«화면에 보이는» 색</b>.
        /// ⚠ <b>배경에서 파생시키지 않는다</b> — W1L5 만 색조가 돌아(`#FF7452`→`#FD9651`)
        /// 「밝기만 올린 값」으로 만들면 그 레벨에서 틀어진다 [05_연출 §1].
        ///
        /// <para>
        /// ★★ <b>[20회차 정정] 「레벨마다 격자색이 있다」는 틀렸다.</b> 원본 <c>Tbg_Grid</c> 의
        /// <b>틴트</b>는 <b>L1~L4 가 전부 (255,255,255)</b> 이고 <b>L5 만 (243,255,77)</b> 이며
        /// 불투명도는 <b>5레벨 전부 0.5</b> 다 [실측 5레벨 × 4시점 = 20 · 변동 0].
        /// 레벨마다 갈리는 것은 <b>틴트가 아니라 그 아래 배경색</b>이다.
        /// </para>
        ///
        /// <para>
        /// ⚠⚠ <b>그러니 이 컬럼을 «합성식으로 유도하지 마라».</b> 원본 기전은
        /// <c>틴트 × 불투명도 0.5 × 타일 텍스처</c> 인데, 소스 타일 50×50 중 선이 <b>196 px</b> 이라
        /// 화면에서 <b>한 픽셀이 선과 여백을 섞어 그린다</b> — W1L1 을 합성으로 예측하면
