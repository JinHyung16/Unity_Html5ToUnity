namespace JinHyung.BlumgiBounce
{
    /// <summary>한 발의 상태. 원본 실측 거동에서 나온 어휘다.</summary>
    public enum EBlumgiShotState
    {
        /// <summary>
        /// 쏠 수 있는 상태. 누르면 <see cref="Charging"/>.
        /// <para>
        /// ⚠ <b>공이 블롭 머리 위에 있는 것이 아니다</b> [6회차 실측] — 물리 공은 <c>(0, 10000)</c> 에서
        /// 떨어지는 중이고 머리 위의 공은 <b>그림</b>(<c>spr_BallVisu</c>)이다.
        /// <b>홀드가 발사 임계에 못 미쳐 «발사가 안 걸린» 경우도 여기</b>다 — 그때 원본은 아무 일도 하지 않는다.
        /// </para>
        /// </summary>
        Ready = 0,

        /// <summary>
        /// 누르고 있는 중. 블롭이 눌리며 파워가 찬다.
        /// ⚠ <b>원본은 홀드 중에도 시뮬을 멈추지 않는다</b> [실측 `02_시스템_홀드샷.md` §7] —
        /// 정지 게이트를 넣으면 원본과 달라진다.
        /// </summary>
        Charging = 1,

        /// <summary>발사돼 날아가는 중.</summary>
        Flying = 2,

        // ⚠ 3 번 자리는 «비워 둔다». 여기 있던 Dropped(「임펄스 없이 놓인다」)는 6회차 실측이 지웠다 —
        //   임계 미만 홀드는 «놓이는» 것이 아니라 **발사 자체가 안 걸린다** (공은 대기 자리에서 계속 낙하).
        //   그 갈래는 이제 Ready 로 돌아간다. 값을 당기면 저장된 숫자와 어긋날 수 있어 자리만 비운다.

        /// <summary>골인. 원본은 여기서 다음 레벨로 넘어간다.</summary>
        Scored = 4,

        /// <summary>화면 밖으로 떨어졌다. <b>실패 패널티는 없다</b> [실측] — 같은 레벨에서 재장전한다.</summary>
        Missed = 5,
    }
}
